#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SetupCategory {
    SystemKernel,
    DevTools,
    Productivity,
    CosmicDesktop,
    RemoteWork,
    GamingMedia,
}

impl SetupCategory {
    pub fn label(self) -> &'static str {
        match self {
            Self::SystemKernel => "Sistema & Kernel",
            Self::DevTools => "Dev & IDEs",
            Self::Productivity => "Produtividade & Office",
            Self::CosmicDesktop => "COSMIC & Periféricos",
            Self::RemoteWork => "Trabalho Remoto & Rede",
            Self::GamingMedia => "Jogos & Mídia",
        }
    }
}

